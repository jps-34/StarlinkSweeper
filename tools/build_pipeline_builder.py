#!/usr/bin/env python3
"""Generates scripts/StarlinkSweeper-PipelineBuilder.js.

WBPP evaluates a pipeline builder from one file, where #include is not available:
the builder is therefore the concatenation of the detection and masking sources.
Maintenance tool only: Python is not part of the product.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = os.path.join(ROOT, "scripts")


def read(name):
    with open(os.path.join(S, name), encoding="utf-8") as f:
        return f.read()


HEADER = """/*
 * StarlinkSweeper-PipelineBuilder.js
 * Copyright (c) 2026 Jacques Pouyaud.
 * SPDX-License-Identifier: GPL-3.0-or-later
 * Free software under the GNU General Public License, version 3 or (at your
 * option) any later version, WITHOUT ANY WARRANTY; see LICENSE.
 * Code written by Claude (Anthropic), under the direction of Jacques Pouyaud.
 * https://github.com/jps-34/StarlinkSweeper
 *
 * WBPP pipeline builder: WBPP > Pipeline tab > Pipeline builder, select this file.
 * GENERATED by tools/build_pipeline_builder.py: do not edit.
 */

"""

parts = [
    HEADER,
    "// The scan core declares many top-level names: only its namespace is kept.\n",
    "var StarlinkSweeperScan = ( function() {\n",
    read("StarlinkSweeperCore.js"),
    "\nreturn StarlinkSweeperScan;\n} )();\n\n",
    read("StarlinkSweeperMaskCore.js"),
    "\n",
    read("StarlinkSweeperMaskEngine.js"),
    "\n",
    read("StarlinkSweeperBuilderBody.js"),
]
with open(os.path.join(S, "StarlinkSweeper-PipelineBuilder.js"), "w", encoding="utf-8") as f:
    f.write("".join(parts))
print("scripts/StarlinkSweeper-PipelineBuilder.js written")
